#[cfg(test)]
mod tests {
    use super::WORDS;
    use std::collections::HashSet;

    #[test]
    fn words_are_lowercase_ascii_letters() {
        for word in WORDS {
            assert!(
                word.chars().all(|character| character.is_ascii_lowercase()),
                "word {word:?} must be lowercase ASCII letters"
            );
        }
    }

    #[test]
    fn words_are_unique() {
        let unique: HashSet<_> = WORDS.iter().collect();
        assert_eq!(unique.len(), WORDS.len(), "word list contains duplicates");
    }

    #[test]
    fn word_list_is_large_enough_for_readable_aliases() {
        assert!(
            WORDS.len() >= 128,
            "word list is too small: {}",
            WORDS.len()
        );
    }
}
