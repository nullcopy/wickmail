//! Alias identity and stored lease policy.

use std::fmt;
use std::str::FromStr;

use serde::{Deserialize, Serialize};
use time::Duration;
use uuid::Uuid;

use crate::address::CanonicalAddress;
use crate::timestamp::Timestamp;

/// Default lease duration: seven days.
pub const DEFAULT_LEASE_SECONDS: i64 = 7 * 24 * 60 * 60;

/// Stable internal identifier for an alias.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(transparent)]
pub struct AliasId(Uuid);

impl AliasId {
    /// Generates a new random identifier.
    pub fn new() -> Self {
        Self(Uuid::new_v4())
    }

    /// Wraps an existing UUID.
    pub fn from_uuid(value: Uuid) -> Self {
        Self(value)
    }

    /// The underlying UUID.
    pub fn as_uuid(self) -> Uuid {
        self.0
    }
}

impl Default for AliasId {
    fn default() -> Self {
        Self::new()
    }
}

impl fmt::Display for AliasId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

impl FromStr for AliasId {
    type Err = uuid::Error;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        Uuid::parse_str(value).map(Self)
    }
}

impl rusqlite::types::FromSql for AliasId {
    fn column_result(value: rusqlite::types::ValueRef<'_>) -> rusqlite::types::FromSqlResult<Self> {
        let text = value.as_str()?;
        AliasId::from_str(text)
            .map_err(|error| rusqlite::types::FromSqlError::Other(Box::new(error)))
    }
}

impl rusqlite::types::ToSql for AliasId {
    fn to_sql(&self) -> rusqlite::Result<rusqlite::types::ToSqlOutput<'_>> {
        Ok(rusqlite::types::ToSqlOutput::from(self.0.to_string()))
    }
}

/// Effective lifecycle state, computed at evaluation time.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AliasState {
    /// Deliverable: not disabled and not expired.
    Active,
    /// The lease has passed; delivery is quarantined.
    Expired,
    /// Explicitly turned off; recipients are rejected.
    Disabled,
}

/// A stored alias and its lease policy.
///
/// The address is generated by the server and carries no policy. Expiry,
/// renewal, and enabled state live only in these stored fields, so changing
/// policy never changes the address.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Alias {
    /// Stable internal identifier.
    pub id: AliasId,
    /// Canonical unique full address.
    pub address: CanonicalAddress,
    /// User-facing name.
    pub label: Option<String>,
    /// Optional order, merchant, or notes field.
    pub purpose: Option<String>,
    /// Creation timestamp.
    pub created_at: Timestamp,
    /// Absolute expiry; `None` means no expiry.
    pub expires_at: Option<Timestamp>,
    /// When the alias was disabled; `None` when enabled.
    pub disabled_at: Option<Timestamp>,
    /// Renewal duration used when a renewal does not specify one.
    pub lease_duration_seconds: i64,
    /// Whether authenticated outbound mail renews the lease.
    pub renew_on_outbound: bool,
    /// Most recent accepted inbound mail; informational only.
    pub last_inbound_at: Option<Timestamp>,
    /// Most recent user activity that renews or extends the lease.
    pub last_user_activity_at: Option<Timestamp>,
    /// Optimistic concurrency version, incremented on every mutation.
    pub policy_version: i64,
}

impl Alias {
    /// The renewal duration as a [`Duration`].
    pub fn lease_duration(&self) -> Duration {
        Duration::seconds(self.lease_duration_seconds)
    }

    /// The last-used time for "recently used" sorting.
    ///
    /// The later of inbound mail and user activity, falling back to the
    /// creation time when neither is present.
    pub fn last_used_at(&self) -> Timestamp {
        match (self.last_inbound_at, self.last_user_activity_at) {
            (Some(inbound), Some(activity)) => inbound.max(activity),
            (Some(inbound), None) => inbound,
            (None, Some(activity)) => activity,
            (None, None) => self.created_at,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::{Alias, AliasId, DEFAULT_LEASE_SECONDS};
    use crate::address::CanonicalAddress;
    use crate::timestamp::Timestamp;

    fn alias() -> Alias {
        Alias {
            id: AliasId::from_uuid("018f9b60-0000-7000-8000-000000000000".parse().unwrap()),
            address: CanonicalAddress::parse("green.farm@example.com").unwrap(),
            label: None,
            purpose: None,
            created_at: "2026-01-01T00:00:00Z".parse().unwrap(),
            expires_at: None,
            disabled_at: None,
            lease_duration_seconds: DEFAULT_LEASE_SECONDS,
            renew_on_outbound: true,
            last_inbound_at: None,
            last_user_activity_at: None,
            policy_version: 0,
        }
    }

    #[test]
    fn last_used_falls_back_to_creation() {
        assert_eq!(alias().last_used_at(), alias().created_at);
    }

    #[test]
    fn last_used_takes_the_later_timestamp() {
        let mut value = alias();
        value.last_inbound_at = Some("2026-02-01T00:00:00Z".parse().unwrap());
        value.last_user_activity_at = Some("2026-03-01T00:00:00Z".parse().unwrap());
        assert_eq!(
            value.last_used_at(),
            "2026-03-01T00:00:00Z".parse::<Timestamp>().unwrap()
        );
    }
}
